"""Generate compact 64x32 flash clips from the original palette sequences."""
import re
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def encode(colors):
    raw = bytes(colors)
    rle = bytearray()
    i = 0
    while i < len(raw):
        end = i + 1
        while end < len(raw) and raw[end] == raw[i] and end - i < 255:
            end += 1
        rle.extend((end - i, raw[i]))
        i = end
    return bytes([1]) + rle if len(rle) < len(raw) else bytes([0]) + raw

def convert(name):
    text = (ROOT / 'src/Flash/ImageSequences' / (name + '.h')).read_text()
    w, h = map(int, re.search(r'Image\(frame\w+, rgbColors, (\d+), (\d+),', text).groups())
    palette = [int(x) for x in re.search(r'::rgbColors\[\].*?=\s*\{([^}]+)', text).group(1).split(',') if x.strip()]
    frames = re.findall(r'::frame\w+\[\].*?=\s*\{([^}]+)', text)
    out = bytearray(b'PTM1' + bytes((64, 32)) + struct.pack('<HI', len(frames), 0))
    scale = min(64 / w, 32 / h)
    dw, dh = max(1, round(w * scale)), max(1, round(h * scale))
    for frame in frames:
        indices = bytes(int(x) for x in frame.split(',') if x.strip())
        assert len(indices) == w * h
        colors = [0] * 2048
        for y in range(dh):
            for x in range(dw):
                p = indices[min(h - 1, int(y / scale)) * w + min(w - 1, int(x / scale))] * 3
                r, g, b = palette[p:p + 3]
                colors[(y + (32 - dh) // 2) * 64 + x + (64 - dw) // 2] = (r & 224) | ((g >> 3) & 28) | (b >> 6)
        payload = encode(colors)
        out += struct.pack('<HH', 50, len(payload)) + payload
    return out

def main():
    lines = ['// Generated by tools/pack_builtin_media.py; do not edit.', '#pragma once', '#include <cstdint>', 'namespace BuiltinMedia {', 'struct Clip { const char* name; const uint8_t* data; uint32_t size; };']
    names = ('Wave', 'Hex', 'Orb')
    for name in names:
        data = convert(name)
        print(name, len(data), 'bytes')
        lines.append('inline const uint8_t ' + name + '[] = {')
        lines.extend('    ' + ','.join(str(v) for v in data[i:i + 64]) + ',' for i in range(0, len(data), 64))
        lines.append('};')
    lines.append('inline const Clip Clips[] = {' + ','.join('{"' + n.lower() + '",' + n + ',sizeof(' + n + ')}' for n in names) + '};')
    lines.append('}')
    (ROOT / 'src/Media/BuiltinMedia.h').write_text('\n'.join(lines) + '\n')

if __name__ == '__main__':
    main()
